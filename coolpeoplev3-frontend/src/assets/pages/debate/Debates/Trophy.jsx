// The mark: the silhouette with its lit passes stacked on top, plus the soft
// disc on the floor that sits her down rather than leaving her floating.
//
// The viewBox is cropped to the art's own bounds (the drawing sits inside a
// wide empty 630x670 frame; using that frame whole would shrink her by a
// quarter at every call site for nothing). `size` is her height, matching what
// the old cup did with its square box, so no caller had to change.
//
// Unlike the cup, this glyph carries its own gold and ignores `currentColor` —
// so the muted "leading" state is handled in CSS with a filter instead. See
// .dbt-crown--leading in DebateCards.css: a leader has not won anything, and
// the board must not gild them as though they had.
function Trophy({ size = 22, className = '' }) {
    // Unique per instance: several trophies can share a page, and duplicate
    // ids would be invalid even though every instance paints the same gradient.
    const groundId = `trophy-ground-${useId()}`

    return (
        <svg
            className={`trophy ${className}`}
            viewBox="20 20 543 632"
            width={(size * 543) / 632}
            height={size}
            aria-hidden="true"
        >
            <defs>
                <radialGradient id={groundId} cx=".5" cy=".5" r=".5">
                    <stop offset="0" stopColor="#8a6a20" stopOpacity=".40" />
                    <stop offset="1" stopColor="#8a6a20" stopOpacity="0" />
                </radialGradient>
            </defs>
            <ellipse cx="428" cy="633" rx="81" ry="11" fill={`url(#${groundId})`} />
            <g transform="translate(0,670) scale(0.1,-0.1)">
                {STATUE.map(([fill, d]) => (
                    <path key={fill} d={d} fill={fill} />
                ))}
            </g>
        </svg>
    )
}

export default Trophy
